"""Export Spotlight browser assets without importing the desktop search runtime."""

from __future__ import annotations

import ast
import hashlib
import json
from html import escape
from pathlib import Path
import sys


def export_spotlight(root: Path, destination: Path) -> None:
    sys.path.insert(0, str(root.resolve(strict=True)))
    from care_platform.search_presentation import SEARCH_EMBLEM, SEARCH_EXAMPLES, SEARCH_STYLES

    source = (root / "care_platform/global_shortcuts.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    assignment = next(node for node in tree.body if isinstance(node, ast.Assign)
                      and any(getattr(target, "id", "") == "_GLOBAL_SHORTCUTS" for target in node.targets))
    examples = "".join(
        f'<button type="button" data-example="{escape(query, quote=True)}" '
        f'title="{escape(query, quote=True)}" aria-label="Try {escape(query, quote=True)}">{escape(label)}</button>'
        for label, query in SEARCH_EXAMPLES
    )
    assets = {}
    for argument in assignment.value.keywords:
        if argument.arg in {"html", "css", "js"}:
            assets[argument.arg] = eval(
                compile(ast.Expression(argument.value), "spotlight browser assets", "eval"),
                {"__builtins__": {}, "SEARCH_EMBLEM": SEARCH_EMBLEM, "SEARCH_STYLES": SEARCH_STYLES,
                 "_EXAMPLE_BUTTONS": examples},
            )
    destination.mkdir(exist_ok=True)
    (destination / "spotlight.mjs").write_text(
        "// Generated by export_native_spotlight.py from CARE's desktop browser component.\n"
        + f'export const html = {json.dumps(assets["html"], ensure_ascii=False)};\n'
        + f'export const css = {json.dumps(assets["css"], ensure_ascii=False)};\n'
        + assets["js"],
        encoding="utf-8",
    )
    (destination / "spotlight-version.json").write_text(json.dumps({
        "source": "care_platform/global_shortcuts.py",
        "assets": {name: hashlib.sha256(value.encode("utf-8")).hexdigest() for name, value in assets.items()},
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    site = Path(__file__).resolve().parents[1]
    workspace = Path(sys.argv[1]) if len(sys.argv) > 1 else site.parents[1]
    export_spotlight(workspace, site / "native")
