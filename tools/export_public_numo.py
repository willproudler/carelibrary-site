"""Export the web NUMO reference shelves from explicit desktop sources."""

import json
from pathlib import Path
import sys


SITE_ROOT = Path(__file__).resolve().parents[1]
CARE_ROOT = SITE_ROOT.parents[1]
sys.path.insert(0, str(CARE_ROOT))

from care_numo.pandemonium import load_release
from care_platform.beta_catalogue import read_catalogue
from care_platform.numo_correspondence_chambers import load_correspondence_chambers
from care_platform.numo_instrument_data import build_numo_instrument_data
from care_platform.numo_library_data import CHAMBER_AUDIT_FILE, load_numo_library_world


SHELF_IDS = {
    "Philosopher’s Tarot": "philosophers-tarot",
    "Acéphalous Tarot": "acephalous-tarot",
    "Disco Elysium skills": "disco-skills",
}


def select(record, keys):
    return {key: record[key] for key in keys if key in record}


def public_books_by_demon(demon_ids):
    """Export only exact work IDs already present in the published catalogue."""
    approved_ids = {work["id"] for work in read_catalogue(SITE_ROOT)["works"]}
    linked_books = {}
    for book in load_numo_library_world(root=CARE_ROOT)["books"]:
        if book["id"] not in approved_ids:
            continue
        for demon_id in book["demon_ids"]:
            if demon_id in demon_ids:
                linked_books.setdefault(demon_id, []).append(book["id"])
    return {demon_id: sorted(ids) for demon_id, ids in sorted(linked_books.items())}


def export_world():
    audit = json.loads((CARE_ROOT / CHAMBER_AUDIT_FILE).read_text(encoding="utf-8"))
    attribution = select(audit, ("title", "attribution", "date"))
    shelves = []
    for shelf in load_correspondence_chambers(CARE_ROOT, chamber_audit=audit):
        shelf_id = SHELF_IDS[shelf["label"]]
        shelves.append({
            **select(shelf, ("kind", "label", "title")),
            "id": shelf_id,
            "entries": [{
                **select(entry, ("name", "group", "number", "subject", "card_position")),
                "id": f"{shelf_id}:{entry.get('card_position') or entry['number']}",
            } for entry in shelf["entries"]],
        })
    demons = []
    for record in load_release()["demons"]:
        identity = record["mesh_id"]
        span = record["net_span"]
        chamber = audit["entries"].get(identity, {})
        links = chamber.get("deck_links", []) if chamber.get("net_span") == span["code"] else []
        demons.append({
            **select(record, ("name", "aliases", "epithet", "domain", "demon_class", "pitch", "phase_limit")),
            "id": identity,
            "number": record["mesh_number"],
            "net_span": span["code"],
            "poles": [span["primary_pole"], span["secondary_pole"]],
            "door": select(record.get("door") or {}, ("number", "name", "correspondence", "location")),
            "relations": [select(row, ("relation", "target", "targets")) for row in record["relations"]],
            "rites": [{
                "id": f"{identity}.{rite['rite_id']}", "rite_id": rite["rite_id"],
                "code": str(rite.get("sequence") or ""), "zones": rite.get("zone_sequence") or [],
                "calculable": bool(rite.get("zone_sequence")),
            } for rite in record["rites"]],
            # Use the shared projection for links and footprints. Only the
            # correspondence itself is published here, with its attribution.
            "chamber_audit": {"sections": [], "deck_links": [{
                **select(link, ("system", "key", "relation", "section")),
                "detail": link["relation"].replace("_", " ").capitalize(),
            } for link in links]},
        })
    world = {"demons": demons, "correspondence_chambers": shelves, "chamber_audit": attribution}
    world["instrument"] = build_numo_instrument_data(world)
    for demon in demons:
        del demon["chamber_audit"]
    world["public_books_by_demon"] = public_books_by_demon({demon["id"] for demon in demons})
    return world


if __name__ == "__main__":
    world = export_world()
    counts = {shelf["id"]: len(shelf["entries"]) for shelf in world["correspondence_chambers"]}
    assert counts == {"philosophers-tarot": 78, "acephalous-tarot": 78, "disco-skills": 24}
    assert len(world["demons"]) == len({demon["id"] for demon in world["demons"]}) == 45
    target = SITE_ROOT / "native/numogram-reference.mjs"
    target.write_text(
        "// Generated by tools/export_public_numo.py.\nexport default "
        + json.dumps(world, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Exported {len(world['demons'])} demons and {sum(counts.values())} deck entries.")
