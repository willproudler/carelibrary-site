"""Export only the browser assets used by the local in-app CARE Reader."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys


def export_reader(root: Path, destination: Path) -> None:
    sys.path.insert(0, str(root.resolve(strict=True)))
    from care_platform.writing_review_browser_assets import reader_browser_assets

    template, css, js = reader_browser_assets(in_app=True)
    assets = {"template": template, "css": css, "js": js}
    mode_position_source = Path("care_platform/writing_editor/mode_position.js")
    mode_position = (root / mode_position_source).read_text(encoding="utf-8")
    destination.mkdir(exist_ok=True)
    (destination / "writing-reader-assets.mjs").write_text(
        "// Generated by export_native_draft_reader.py. Do not edit.\n"
        "export default Object.freeze(" + json.dumps(assets, ensure_ascii=False, separators=(",", ":")) + ");\n"
        + mode_position
        + "export {rememberWritingModePosition, takeWritingModePosition, restoreWritingModePosition};\n",
        encoding="utf-8",
    )
    (destination / "writing-reader-version.json").write_text(json.dumps({
        "source": "care_platform/writing_review_browser_assets.py",
        "mode_position_source": str(mode_position_source),
        "assets": {name: hashlib.sha256(value.encode("utf-8")).hexdigest() for name, value in assets.items()},
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    release = Path(__file__).resolve().parents[1]
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else release.parents[1]
    export_reader(root, release / "native")
